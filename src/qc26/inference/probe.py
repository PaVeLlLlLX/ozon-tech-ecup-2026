"""Зонды-измерители: передают число из контейнера через публичный балл.

Контейнер видит закрытую выборку, но не видит меток и не может ничего записать наружу,
кроме файла ответов. Значит любой замер по закрытым данным приходится передавать
кодированием в самих вердиктах, а читать — по публичному баллу.

**Состав публичной выборки восстановлен точно** из двух уже сделанных отправок. Балл
публикуется с десятью знаками, а под ним отношение целых чисел, поэтому целочисленный
перебор оставил единственную раскладку, сошедшуюся с обоими зондами до девятого знака:

    БАД     921 товар, 528 «не бан»   (доля 0.5733)
    редкая  707 товаров, 24 «не бан»  (доля 0.0339)
    всего  1628 товаров

Отсюда канал передачи. Если пометить «не бан» долю f товаров категории БАД, выбранную
по хэшу идентификатора (то есть независимо от метки), а всей редкой категории поставить
«бан», то публичный балл равен

    метрика = 0.5 * F1(БАД) = 528*f / (921*f + 528),

а вклад редкой категории равен нулю. Уровни подобраны так, чтобы значения метрики шли
с равным шагом 0.045 — это примерно семь стандартных отклонений случайности выбора,
поэтому уровень читается однозначно.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

import numpy as np
import pandas as pd

# Замеренный состав публичной выборки (см. заголовок модуля).
PUBLIC = {"БАД": (921, 528), "Легковоспламеняющиеся": (707, 24)}

# Доли категории БАД под равномерный шаг метрики 0.045. Уровень 0 — ничего не помечено.
FRACTIONS = [0.0, 0.0488, 0.1068, 0.1766, 0.2624, 0.3703, 0.5104, 0.6990, 0.9678]


def expected_score(level: int) -> float:
    """Публичный балл, которым уровень отзовётся на лидерборде."""
    n, p = PUBLIC["БАД"]
    f = FRACTIONS[level]
    return p * f / (n * f + p)


def decode_table() -> list[tuple[int, float]]:
    return [(i, expected_score(i)) for i in range(len(FRACTIONS))]


def _unit(item_id: str) -> float:
    """Равномерное число из идентификатора: выбор не должен зависеть от метки."""
    h = hashlib.md5(str(item_id).encode("utf-8")).hexdigest()[:8]
    return int(h, 16) / 0xFFFFFFFF


def bucket(value: float, edges: list[float]) -> int:
    """Номер уровня по границам корзин; значений уровней ровно len(edges)+1."""
    return int(np.searchsorted(np.asarray(edges, dtype=float), float(value), side="right"))


def encode(cfg: dict, df: pd.DataFrame, level: int) -> np.ndarray:
    """Вердикты, кодирующие уровень: доля БАД по хэшу — «не бан», редкая — вся «бан»."""
    level = int(np.clip(level, 0, len(FRACTIONS) - 1))
    f = FRACTIONS[level]
    idc, cat = cfg["data"]["id_col"], cfg["data"]["category_col"]
    is_sup = (df[cat].astype(str) == "БАД").to_numpy()
    picked = np.array([_unit(v) < f for v in df[idc].astype(str)], dtype=bool)
    return (is_sup & picked).astype(int)


# --- сами замеры -----------------------------------------------------------------

# Типы редкой категории, богатые позитивами (EDA-9): доля «не бан» внутри типа от 45.8%
# у спичек и 26.9% у угля до 12.1% у пиротехники при фоне 3.6%. Если в закрытой выборке
# их доля другая, чем у нас, потолок F1 редкой категории там тоже другой.
RICH_TYPES = re.compile(
    r"спичк|спичек|спички|уголь|древесн\w* уголь|розжиг|растопк|сухое горюч"
    r"|хлопушк|петард|фейерверк|салют|бенгальск", re.IGNORECASE)

# Границы корзин под каждый замер. Подобраны вокруг того, что даёт наша модель на своих
# данных, чтобы интересный диапазон приходился на середину шкалы, а не на её край.
MEASURES = {
    # Сколько товаров редкой категории модель зовёт «не бан». Позитивов там ровно 24,
    # F1 известна из обычной отправки — вместе это даёт точность и полноту по отдельности.
    "rare_predpos": {"edges": [7.5, 13.5, 19.5, 25.5, 32.5, 41.5, 53.5, 70.5],
                     "what": "число товаров редкой категории с вердиктом «не бан»"},
    # Доля товаров редкой категории, у которых нашлась хотя бы одна фотография.
    "rare_photos": {"edges": [0.05, 0.20, 0.40, 0.60, 0.75, 0.85, 0.93, 0.98],
                    "what": "доля товаров редкой категории, у которых есть фото"},
    # Доля типов, богатых позитивами.
    "rare_types": {"edges": [0.02, 0.05, 0.08, 0.12, 0.17, 0.24, 0.33, 0.45],
                   "what": "доля товаров редкой категории из типов, богатых позитивами"},
    # Главный вопрос 15.08: делили ли организаторы каталог по товарам или по группам.
    # Если по товарам, у тестового товара его дубликат лежит в нашей обучающей выборке
    # вместе с меткой; на своих данных покрытие редкой категории 67.3% при точности
    # вердикта 99.7%. Если дубликаты разведены, покрытие будет около нуля и ветка пуста.
    # Границы поставлены так, чтобы ноль и наши 67% попали в РАЗНЫЕ края шкалы.
    "rare_dupcov": {"edges": [0.02, 0.08, 0.18, 0.30, 0.42, 0.55, 0.68, 0.80],
                    "what": "доля товаров редкой категории, у которых нашёлся "
                            "почти-дубликат в обучающей выборке"},
}


def measure(name: str, cfg: dict, df: pd.DataFrame, scores=None, images_root=None,
            dup_table=None) -> tuple[float, int]:
    """Значение замера и его уровень."""
    cat = cfg["data"]["category_col"]
    rare = (df[cat].astype(str) != "БАД").to_numpy()

    if name == "rare_predpos":
        if scores is None:
            raise RuntimeError("замеру нужны оценки модели, а они не построены")
        value = float(np.asarray(scores)[rare].sum())
    elif name == "rare_photos":
        from ..data import image_paths

        # ⚠ Ненайденный корень изображений и выборка без фотографий дали бы один и тот же
        # ноль, а выводы из них противоположные. Молчаливое вырождение уже стоило нам
        # трёх попыток, поэтому здесь прогон падает: упавшая отправка попытку не тратит,
        # а тихо вырожденная тратит и вдобавок врёт.
        if images_root is None or not Path(images_root).is_dir():
            raise RuntimeError(f"корень изображений не найден ({images_root}) — "
                               f"замер доли фотографий невозможен")
        idc = cfg["data"]["id_col"]
        ids = df.loc[rare, idc].astype(str)
        if not len(ids):
            raise RuntimeError("в выборке нет товаров редкой категории")
        value = float(np.mean([bool(image_paths(images_root, i)) for i in ids]))
    elif name == "rare_dupcov":
        from .duplicates import lookup

        if dup_table is None:
            raise RuntimeError("замеру нужна таблица подписей, а её нет в архиве")
        hits = lookup(df.loc[rare], dup_table, cfg)
        value = float(hits.notna().mean()) if len(hits) else 0.0
    elif name == "rare_types":
        name_col, desc_col = cfg["data"]["name_col"], cfg["data"]["desc_col"]
        text = (df.loc[rare, name_col].astype(str) + " "
                + df.loc[rare, desc_col].astype(str).str.slice(0, 300))
        value = float(text.str.contains(RICH_TYPES).mean()) if len(text) else 0.0
    else:
        raise KeyError(f"неизвестный замер «{name}»")

    return value, bucket(value, MEASURES[name]["edges"])
