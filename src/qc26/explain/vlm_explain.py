"""Объяснение вердикта, написанное той же моделью, что и выносила вердикт.

## Что здесь происходит

Вердикт УЖЕ принят. Модель его не пересматривает — ей сообщают решение и найденные
правилами улики и просят написать обоснование для проверяющего сотрудника.

⚠ Формулировка НАМЕРЕННО осторожная: модель описывает товар и найденные признаки, но
НЕ объявляет принадлежность к категории. Причина замерена: на выборке из ста товаров
восемь объяснений прямо противоречили вердикту («является источником огня, что
соответствует категории» при вердикте «бан»), и все восемь пришлись на товары, где
вердикт ошибочен. Модель в тексте оказывалась права, а в вердикте нет, и строка читалась
как спор решения с самим собой. Запретить спор нельзя — можно убрать повод: если текст
не выносит суждения о категории, противоречить ему нечему.

## Стоимость

Проход генерации дороже прохода вердикта, и на приватной стадии решение из-за него
не укладывалось в лимит. Поэтому всё, что влияет на время, вынесено в параметры и
замеряется: число кадров, потолок новых токенов, длина описания в промпте, батч.

⚠ Главные траты по убыванию: кадры (каждый добавляет около 118 зрительных токенов),
длина ответа, длина описания. Правила категории в промпт объяснения НЕ подаются: они
занимают около 500 символов и не нужны — решение уже принято, а описывать признаки
можно и без свода правил.
"""
from __future__ import annotations

import re
import time

import pandas as pd

MIN_LEN, MAX_LEN = 50, 300
TARGET_LO, TARGET_HI = 110, 180

# ⚠ Ни слова о принадлежности к категории — см. шапку модуля. Модель называет предмет и
# то, что во второй половине найдено; вывод о категории уже сделан и стоит в отдельном поле ответа.
#
# ⚠ Второе предложение обязано начинаться со слова «Решающее:». Просьба «назови главный
# признак» без такой опоры не работает: витки 02 и 03 отличались формулировкой просьбы и
# дали почти одинаковые тексты — чистое описание товара без единой причины на 22
# проверенных вердиктах «бан». Буквальную приставку модель держит несравнимо надёжнее
# абстрактного указания, а проверяющему причина отдельной фразой даже удобнее.
PROMPT = (
    "Ты модератор маркетплейса. Решение по карточке уже принято другим проверяющим.\n\n"
    "Заявленная категория: «{cat}».\n"
    "Название: {name}\n"
    "Описание: {desc}\n"
    "{evidence}"
    "Изображение товара приложено выше.\n\n"
    "Напиши запись для журнала РОВНО из двух коротких предложений.\n"
    "Первое начни строго со слова «Решающее:» и назови один признак — {hint}\n"
    "Второе: что это за товар, три-шесть слов.\n"
    "По-русски, вместе от {lo} до {hi} символов — короче, чем хочется. Не пиши, "
    "относится товар к категории или нет, и не употребляй слова «бан», «категория», "
    "«соответствует». Признак назови своими словами по этому товару — формулировку "
    "подсказки дословно не повторяй. Вывода не делай.\n"
    "Запись: Решающее:"
)

# Подсказка направления — СВОЯ на категорию и на вердикт.
#
# ⚠ Общая подсказка про «отсутствие маркировки» обошлась дорого: в редкой категории
# модель 17 раз написала «Нет маркировки «легковоспламеняющийся» на устройстве», а
# такой маркировки правила не требуют вовсе — признак выдуман. В БАД про маркировку
# писать верно, потому что правило именно о ней; в редкой решает содержимое и назначение
# предмета, и подсказка обязана давать модели ровно этот словарь.
HINT = {
    # ⚠ Подсказка БАД — ОДНА на оба вердикта, как и в редкой. Меню из трёх поводов
    # («нет маркировки, либо спортпитание, либо прямо сказано что не БАД») толкало модель
    # выбирать любой и подгонять карточку под выбор: «кордицепс обозначен как спортивное
    # питание», хотя не обозначен. Чистый же вопрос «что написано о виде товара» увёл в
    # другую крайность: пошли цитаты этикетки без связи с решением — «указано «порошок
    # очищенный»». Нужен вопрос фактический, но по существу правила: есть ли слова
    # маркировки добавки и чем товар назван по виду.
    ("БАД", 1): "есть ли в тексте или на упаковке слова «БАД», «биологически активная "
                "добавка», «dietary supplement», и чем товар назван по виду: добавка, "
                "спортивное питание, лекарство, косметика, принадлежность. Пиши только "
                "то, что действительно видишь.",
    ("БАД", 0): "есть ли в тексте или на упаковке слова «БАД», «биологически активная "
                "добавка», «dietary supplement», и чем товар назван по виду: добавка, "
                "спортивное питание, лекарство, косметика, принадлежность. Пиши только "
                "то, что действительно видишь.",
    # ⚠ В редкой категории подсказка ОДНА на оба вердикта и намеренно нейтральна.
    # Когда она была разной, модель на ошибочных вердиктах сочиняла неправду, лишь бы
    # оправдать решение: «горелка не требует внешнего источника горючего, работает от
    # пьезоподжига» (пьезо — это поджиг, а не топливо), «хлопушка — устройство для
    # создания огня без внешнего источника». Спрашиваем только факт: что внутри и как
    # работает. Для мангала ответ «своего топлива нет, только корпус и решётка» и есть
    # причина решения; для ошибочно забаненной дымовой шашки ответ «содержит
    # пиротехнический состав» честен и вердикту текстом не противоречит — вывод
    # проверяющий делает сам.
    # ⚠ Формулировка через «есть ли» толкала модель начинать с отрицания, а потом
    # честно дописывать факт: «Нет собственного горючего содержимого, НО СОДЕРЖИТ
    # топливо для горения». Отрицание и утверждение в одной фразе — худшее, что можно
    # показать проверяющему. Спрашиваем без полярности: что внутри и от чего работает.
    ("Легковоспламеняющиеся", 1): "что находится ВНУТРИ товара и от чего он работает: "
                                  "собственное топливо, газ, пиротехнический состав, "
                                  "спички в комплекте — или внешний источник.",
    # ⚠ Подсказки для обоих вердиктов теперь СОВПАДАЮТ ПОСИМВОЛЬНО, и это обязательное
    # условие: поверх объяснения обучается судья, а если текст хоть немного зависит от
    # вердикта, судья выучит не смысл, а способ прочитать вердикт из формулировки —
    # и на прогоне, где вердикта ещё нет, эти признаки окажутся мёртвыми.
    ("Легковоспламеняющиеся", 0): "что находится ВНУТРИ товара и от чего он работает: "
                                  "собственное топливо, газ, пиротехнический состав, "
                                  "спички в комплекте — или внешний источник.",
}
HINT_ANY = {
    1: "что подтверждает заявленное свойство товара: маркировка, состав, содержимое.",
    0: "чего у товара нет или что расходится с заявленным.",
}

# ⚠ Улики переводятся в человеческие слова. Прежде в промпт уходили служебные имена
# ключей, и модель цитировала их дословно: «Наличие маркировки supplement_mark в
# автоматической системе подтверждает...». Так вышло у 34 объяснений из ста.
EVIDENCE_RU = {
    "supplement_mark_ocr": "на фотографии упаковки видна маркировка пищевой добавки",
    "supplement_mark": "в описании есть слова «биологически активная добавка к пище»",
    "supplement_word": "в карточке встречается слово «БАД»",
    "explicit_not_supplement": "в описании прямо сказано, что это не БАД",
    "sport_nutrition": "карточка называет товар спортивным питанием",
    "fuel_content_name": "в названии указано горючее вещество или газ",
    "fuel_content": "в составе указано горючее вещество",
    "ignition_source_name": "название говорит об источнике открытого огня",
    "in_kit": "горючее содержимое входит в комплект",
    "device_for_fire": "это устройство, работающее с огнём или топливом",
    "accessory": "это принадлежность или тара",
}

_BANNED = re.compile(r"\b(?:не\s+бан|бан|категори\w+|соответству\w+)\b", re.I)
_TAGS = re.compile(r"<[^>]*>")
_KEYS = re.compile("|".join(EVIDENCE_RU))


def _evidence_line(row, rules_mod) -> str:
    """Улики правил человеческими словами. Служебные имена в промпт не попадают."""
    try:
        ev = rules_mod.evidence(row, "")
    except Exception:
        return ""
    hits = [EVIDENCE_RU[k] for k, v in ev.items() if v is True and k in EVIDENCE_RU]
    if not hits:
        return ""
    return "Замечено при проверке: " + "; ".join(hits[:3]) + ".\n"


def _clean(text: str, hit_cap: bool = False) -> str:
    """Приводит сгенерированное к виду, годному для строки ответа.

    hit_cap — генерация упёрлась в потолок новых токенов. Тогда последнее предложение
    почти наверняка недописано, и его надо отбросить независимо от того, как оно
    выглядит: шаблоны по предлогу и цифре ловят не всё, «хлопушка с серпант.» они
    пропускают. Признак надёжнее любого разбора текста — он про сам факт обрыва.
    """
    t = _TAGS.sub(" ", str(text or ""))
    t = re.sub(r"\s+", " ", t).strip()
    t = t.strip('"“”«»').strip()
    t = re.sub(r"^(?:запись|описание|обоснование|ответ|комментарий)\s*[:—-]\s*", "",
               t, flags=re.I)
    # Промпт обрывается на слове «Решающее:», и модель дописывает продолжение. Возвращаем
    # приставку, иначе запись начинается с середины фразы.
    if not t.lower().startswith("решающее"):
        t = "Решающее: " + t[0].lower() + t[1:] if t else t
    # ⚠ Служебное имя улики, если оно всё же просочилось, вырезаем целиком с оборотом.
    if _KEYS.search(t):
        t = re.sub(r"[^.!?]*(?:" + "|".join(EVIDENCE_RU) + r")[^.!?]*[.!?]?", " ", t)
    t = _BANNED.sub("", t)
    t = re.sub(r"\s+", " ", t).strip(" ,;:-")
    if len(t) > MAX_LEN:
        cut = max(t.rfind(". ", 0, MAX_LEN), t.rfind("! ", 0, MAX_LEN),
                  t.rfind("? ", 0, MAX_LEN))
        t = (t[:cut + 1] if cut > MIN_LEN else t[:MAX_LEN].rsplit(" ", 1)[0]).strip()
    # ⚠ Обрыв бывает и без превышения длины: модель упирается в потолок новых токенов и
    # останавливается посреди слова. Недописанное предложение отбрасываем, если без него
    # текст остаётся содержательным.
    if t and t[-1] not in ".!?":
        cut = max(t.rfind(". "), t.rfind("! "), t.rfind("? "))
        if cut >= MIN_LEN:
            t = t[:cut + 1].strip()
    if t and t[-1] not in ".!?":
        t += "."
    # ⚠ Обрыв бывает и с точкой на конце: потолок новых токенов исчерпан посреди мысли,
    # и остаётся «в упаковке 10.» или «с 50+ ингредиентами и.». Формат такое пропускает,
    # человек читает как брак. Предлог, число или косая черта перед точкой — признак
    # недописанной фразы; откатываемся к границе предложения, а если её нет — к запятой.
    if hit_cap or re.search(
            r"(?:\b(?:до|от|и|или|с|в|на|по|для|около|более|менее)|\d|/)\.$", t):
        cut = max(t.rfind(". ", 0, len(t) - 2), t.rfind("! ", 0, len(t) - 2))
        if cut >= MIN_LEN:
            t = t[:cut + 1].strip()
        else:
            c2 = t.rfind(", ")
            if c2 >= MIN_LEN:
                t = t[:c2].rstrip(" ,;:-") + "."
    # ⚠ Хвостовая пустышка чистится В САМОМ КОНЦЕ, после всех обрезок. Стояла раньше —
    # и не работала: обрезка по потолку откатывала текст к границе предложения, пустышка
    # снова оказывалась последней, а чистить её было уже некому. Так она уцелела у
    # четырёх объяснений витка 11.
    t = re.sub(r"[,;]?\s*(?:но )?(?:не указано|не уточняется|отсутствует утверждение|"
               r"информация отсутствует|а также)\s*\.?$", ".", t, flags=re.I).strip()
    t = re.sub(r"[\s,;:-]+\.$", ".", t)
    return t


def generate_comments(df: pd.DataFrame, cfg: dict, images_root, runner, preds,
                      fallback: list[str], *, max_new_tokens: int = 64,
                      n_images: int = 1, max_desc: int = 350,
                      batch: int | None = None, stats: dict | None = None) -> list[str]:
    """Комментарий на каждый товар. Где генерация не прошла проверку — шаблон.

    n_images    сколько кадров подать. Один вместо пяти убирает около 470 зрительных
                токенов на товар; упаковка при этом видна — маркировка почти всегда
                на первом кадре.
    max_desc    сколько символов описания класть в промпт.
    stats       если передать словарь, туда лягут замеры длин и времени.
    """
    from .. import rules as rules_mod
    from ..inference.vlm import MAX_NAME, _load_image, _paths

    torch = runner.torch
    d = cfg["data"]
    idc, cat_col = d["id_col"], d["category_col"]
    runner.model.config.use_cache = True
    tok = runner.tok
    out: list[str] = []
    used_fallback = 0
    n_prompt_tok = n_new_tok = 0
    t0 = time.time()
    # ⚠ У генерации СВОЙ расчёт батча, а не наследование боевого. Боевой считается по
    # свободной видеопамяти при ПЯТИ кадрах, а объяснение подаётся с ОДНИМ — памяти на
    # товар нужно в разы меньше. Наследование стоило бы вдвое: на H100 боевой батч
    # упирается в потолок 32 из конфига, а с одним кадром туда влезает 64.
    #
    # ⚠ Нижняя граница 16 обязательна. Локально расчёт вырождается: драйвер после
    # загрузки весов сообщает «свободно 0.00 ГБ из 8», и батч падает до единицы, хотя
    # замер показал, что 16 проходит без единого сбоя и ускоряет генерацию с 9.3 до 3.5
    # секунды на товар — в 2.7 раза на ровном месте. Расчёт по памяти здесь занижает,
    # а не завышает, поэтому пол безопаснее потолка.
    if batch:
        bs = int(batch)
    else:
        from ..inference.vlm import auto_batch

        bs = max(16, auto_batch(runner.model.device, n_images, asked=64,
                                max_pixels=runner.px))

    for start in range(0, len(df), bs):
        chunk = df.iloc[start:start + bs]
        prompts, images, order = [], [], []
        for pos, (_, row) in enumerate(chunk.iterrows()):
            imgs = []
            for p in _paths(images_root, str(row[idc]), n_images):
                try:
                    imgs.append(_load_image(p, runner.step, runner.px))
                except Exception:
                    pass
            v = int(preds[start + pos])
            text = PROMPT.format(
                cat=str(row[cat_col]),
                name=str(row[d["name_col"]])[:MAX_NAME],
                desc=str(row.get(d["desc_col"]) or "")[:max_desc],
                evidence=_evidence_line(row, rules_mod),
                hint=HINT.get((str(row[cat_col]), v), HINT_ANY[v]),
                lo=TARGET_LO, hi=TARGET_HI)
            prompts.append(runner._wrap(text, len(imgs)))
            images.append(imgs)
            order.append(start + pos)

        texts = [""] * len(prompts)
        caps = [False] * len(prompts)
        try:
            flat = [im for im in images if im]
            enc = runner.proc(text=prompts, images=flat or None, padding=True,
                              return_tensors="pt").to(runner.model.device)
            n_prompt_tok += int(enc["input_ids"].numel())
            with torch.no_grad():
                gen = runner.model.generate(**enc, max_new_tokens=max_new_tokens,
                                            do_sample=False, num_beams=1,
                                            pad_token_id=tok.pad_token_id)
            new = gen[:, enc["input_ids"].shape[1]:]
            n_new_tok += int((new != tok.pad_token_id).sum())
            # ⚠ Кто упёрся в потолок — тот недописан. Считаем поштучно: в среднем по
            # батчу этого не видно, а обрубок остаётся у конкретного товара.
            caps = [int((row != tok.pad_token_id).sum()) >= max_new_tokens
                    for row in new]
            texts = tok.batch_decode(new, skip_special_tokens=True)
        except Exception as e:
            # ⚠ Падение батча генерации не роняет решение: комментарий имеет законный
            # запасной вид, а вердикт от него не зависит. Молчать всё равно нельзя.
            print(f"сбой генерации на батче {start} ({type(e).__name__}): "
                  f"{str(e)[:120]}", flush=True)

        for k, raw in enumerate(texts):
            got = _clean(raw, hit_cap=caps[k] if k < len(caps) else False)
            if len(got) < MIN_LEN:
                got = fallback[order[k]]
                used_fallback += 1
            out.append(got)

        for im in images:
            for x in im:
                try:
                    x.close()
                except Exception:
                    pass

    if len(out) != len(df):
        raise RuntimeError(f"объяснений {len(out)} на {len(df)} строк")
    dt = time.time() - t0
    share = used_fallback / max(1, len(df))
    if stats is not None:
        stats.update({"секунд": round(dt, 1), "секунд_на_товар": round(dt / len(df), 2),
                      "токенов_промпта_на_товар": round(n_prompt_tok / len(df), 1),
                      "новых_токенов_на_товар": round(n_new_tok / len(df), 1),
                      "кадров": n_images, "потолок_новых": max_new_tokens,
                      "батч": bs, "макс_описание": max_desc,
                      "шаблоном": used_fallback})
    print(f"объяснения за {dt / 60:.1f} мин ({dt / len(df):.2f} с/товар): "
          f"моделью {len(df) - used_fallback}, шаблоном {used_fallback} "
          f"({share * 100:.1f}%); токенов промпта {n_prompt_tok / len(df):.0f}, "
          f"новых {n_new_tok / len(df):.0f} на товар", flush=True)
    # ⚠⚠ ПРОВЕРКА ОБЯЗАНА ЗНАТЬ РАЗМЕР ВЫБОРКИ. Генерация зовётся ПО КАТЕГОРИЯМ, и на
    # стадии проверки в редкой категории бывает три товара: два неудачных текста дают
    # 67% и убивают весь прогон. Долю можно считать приговором только там, где она
    # что-то значит. Ровно на таком же недосмотре — воротах без условия на размер —
    # уже сорвалась одна отправка.
    if share > 0.5 and len(df) >= 50:
        raise RuntimeError(f"генерация не состоялась: шаблоном {share:.0%} объяснений")
    if share > 0.5:
        print(f"   ⚠ шаблоном {share:.0%} на {len(df)} товарах — для приговора мало, "
              f"продолжаю", flush=True)
    return out
