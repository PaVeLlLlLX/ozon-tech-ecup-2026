"""Факты из карточки для промпта: наблюдения, а не вердикты.

## Зачем это, если правила как классификатор провалились

Замерено: правила-улики дают F1 0.098 в роли классификатора, а их узлы как детекторы
позитивов имеют подъём к базе 1.08 — то есть практически не помогают. Попытка использовать
их жёстким фильтром тоже не сработала: отсеивание 512 товаров узлом «устройство для огня»
уносило четыре товара из топ-30 и обходилось в 7 пунктов F1.

Но это провалы правил в роли РЕШАЮЩИХ экспертов. Здесь контекст принципиально иной: факт
кладётся в промпт как наблюдение, окончательное решение принимает нейросетевая модель.
Она вправе пренебречь наблюдением — и это полностью законный исход, а не поломка. Слово
«Замечено» вместо директивного «товар не относится» выбрано не случайно: приказ модель
обязана исполнить, а наблюдение — лишь взвесить.

## Отбор: только замеренное и надёжное

Каждый факт ниже прошёл замер на всей выборке. Критерий отбора: подъём доли позитивов
относительно базовой ВЫШЕ 2.5 либо НИЖЕ 0.25, при МИНИМАЛЬНОМ покрытии сорок товаров.
Всё остальное выброшено как шум — добавляет только длину промпта, не добавляя различения.

Примеры отклонённых кандидатов:
    «+ баллон / в комплекте»  подъём 1.43 — регулярка не разбирает «идёт в комплекте»
                              от «работает от»; именно этот узел давил на точность v2;
    «для розжига»             1.55;  «одноразовый» 1.45;  «штук в названии» 1.81;
    «пиротехническое»         0.53;  «электрическое» 0.35;  «вес/объём» 1.43.

В категории БАД оставлен только один факт: маркировка встречается у 78% товаров при
подъёме 1.10. Остальное (спортпит 0.82, капсулы 1.06) выброшено. Парадокс: там критерий —
не наличие маркировки, а её ОТСУТСТВИЕ, что регулярным выражением не ловится.

## Ограничения и дефекты фактов

Каждый факт опирается на регулярные выражения, которые могут ошибаться:
  — омонимия: слово может встретиться в несвязанном контексте (например, «газ» в описании
    процесса доставки, а не вещества);
  — неполнота: структурированные данные (атрибуты) в карточке не парсятся, доступны только
    текст названия и описания;
  — сезонность и тренды: замеры проводились на снимке выборки; если категория товаров
    изменилась, факт может потерять силу.

Модель обучена видеть эти погрешности и компенсировать их, но достоверность факта падает
при редком срабатывании (менее 50 случаев на выборке).

## Обязательное условие применения: согласованность обучения и инференса

Блок фактов должен присутствовать ОДИНАКОВО при обучении и на инференсе. Добавить его только
на прогоне — это подать на вход информацию из другого распределения.

Абляция показала чувствительность модели к структуре промпта:
  — удаление блока правил целиком снижает покрытие из 9 на 30 до 1 на 30;
  — подмена текста фактов на текст из другой категории деградирует слабее (8 на 30).
  — но добавление блока ТОЛЬКО на инференсе портит результаты молча.

Аналогичную подводу уже пережили с числом фотографий: несовпадение между обучением
и прогоном ломало вердикт без явной ошибки.
"""
from __future__ import annotations

import re

import pandas as pd

# (ключ, формулировка для промпта, где искать, шаблон, замеренный подъём)
# «имя» — искать только в названии: в описании эти слова встречаются у чего угодно
# и признак вырождается в шум.
FACTS_RARE = [
    # --- признаки, при которых позитивов почти НЕТ ---
    ("no_fire_near", "в описании есть предупреждение хранить вдали от огня",
     "полный", r"вдали от (?:огня|источник)|беречь от огня|огнеопасн", 0.00),
    ("no_kit", "в описании оговорено, что горючее или баллон НЕ входит в комплект",
     "полный", r"без баллона|без газа|без спичек|без топлив|без угл[яе]|"
     r"не вход(?:ит|ят)|не включен|в комплект не|баллон не |газ не входит", 0.03),
    ("adapter", "у товара есть переходник или адаптер под внешний баллон",
     "полный", r"переходник|адаптер", 0.07),
    ("piezo", "у товара есть пьезоподжиг",
     "полный", r"пьезо", 0.16),
    ("device_head", "название начинается с устройства: плита, мангал, гриль, горелка",
     "имя", r"^\s*(?:газов\w+\s+)?(?:плит\w+|мангал\w*|грил[ья]?|барбекю|горелк\w+|"
     r"печ[ьи]|коптильн\w+|таганок)", 0.17),
    # --- признаки, при которых позитивов заметно БОЛЬШЕ ---
    ("gost", "в карточке указан ГОСТ",
     "полный", r"\bгост\b", 9.67),
    ("refillable", "изделие заправляемое или перезаправляемое",
     "полный", r"заправляем\w+|перезаправ\w+|для заправки", 5.19),
    ("substance_head", "название начинается с самого вещества: уголь, топливо, газ, спички",
     "имя", r"^\s*(?:угол[ья]|уголь|брикет\w*|топлив\w+|газ\b|бензин\w*|спичк\w+|"
     r"розжиг\w*|растопк\w+|сух\w+\s+горюч\w+|жидкость для)", 4.82),
    ("pack_set", "в названии указана упаковка, набор или блок",
     "имя", r"упаковк|набор|блок|компл", 4.26),
    # ⚠ Формулировка исправлена по замеру. Первая версия писала «без заряда» —
    # это была гипотеза, а данные показали ОБРАТНОЕ: подъём 3.60, то есть слова
    # ловят класс товаров, где позитивов БОЛЬШЕ базы. Пишем нейтрально.
    ("popper", "карточка описывает хлопушку, конфетти или серпантин",
     "полный", r"пневматическ\w+|конфетти|серпантин|язычк\w+", 3.60),
]

FACTS_BAD = [
    ("not_supplement",
     "в описании прямо сказано, что товар НЕ является биологически активной добавкой",
     "полный", r"не\s+являе\w*[^.]{0,60}\b(?:бад|биологически активн)", 0.25),
]

BY_CATEGORY = {"Легковоспламеняющиеся": FACTS_RARE, "БАД": FACTS_BAD}
_COMPILED = {c: [(k, t, where, re.compile(p, re.I), lift)
                 for k, t, where, p, lift in v]
             for c, v in BY_CATEGORY.items()}


def facts_for(name: str, desc: str, category: str, ocr: str = "") -> list[str]:
    """Наблюдения по карточке. Пустой список — значит сказать нечего."""
    name = str(name or "")
    full = f"{name} {desc or ''}"
    out = []
    for _key, text, where, rx, _lift in _COMPILED.get(category, []):
        if rx.search(name if where == "имя" else full):
            out.append(text)
    if ocr and str(ocr).strip():
        short = re.sub(r"\s+", " ", str(ocr))[:160].strip()
        if len(short) > 15:
            out.append(f"на фотографиях распознан текст: {short}")
    return out


def facts_block(name: str, desc: str, category: str, ocr: str = "") -> str:
    """Кусок промпта. Пустая строка, если наблюдений нет.

    ⚠ Пустой блок НЕ печатается вовсе. Заголовок без содержания добавил бы структуру
    без информации, а к структуре промпта модель чувствительна.
    """
    items = facts_for(name, desc, category, ocr)
    if not items:
        return ""
    lines = "\n".join(f"- {x}" for x in items)
    return f"Замечено в карточке (наблюдения, могут быть неточны):\n{lines}\n"


def facts_frame(df: pd.DataFrame, cfg: dict, ocr: pd.Series | None = None) -> pd.DataFrame:
    """Матрица срабатываний — чтобы перемерять полезность каждого факта."""
    d = cfg["data"]
    rows = []
    for _, r in df.iterrows():
        cat = str(r[d["category_col"]])
        name, desc = str(r[d["name_col"]]), str(r.get(d["desc_col"]) or "")
        full = f"{name} {desc}"
        rec = {"id": str(r[d["id_col"]]), "cat": cat}
        for key, _t, where, rx, _lift in _COMPILED.get(cat, []):
            rec[key] = bool(rx.search(name if where == "имя" else full))
        rows.append(rec)
    return pd.DataFrame(rows)
